/**
 * Aider-polyglot adapter — board 2 of the public-benchmark ladder.
 *
 * Dataset: Aider-AI/polyglot-benchmark (Exercism exercises, Exercism licenses),
 * fetched at live setup into a gitignored path (`POLYGLOT_ROOT` env or argument):
 *   <root>/<lang>/exercises/practice/<slug>/ — stub + tests + instructions.
 *
 * Scope (honest, toolchain-driven): Python + Rust grade fully offline
 * (python stdlib `unittest`; `cargo test --offline`, zero-dep manifests).
 * Java (gradle wrapper download), JS (npm install), Go/C++ (no toolchain on
 * this machine) are NOT listed — they slot in by adding one language config
 * plus the toolchain, no adapter redesign.
 *
 * Harness honesty: the official 3B Aider number (33.8 Pass@1, Tech Report
 * Table 19) is the ORIGINAL 133-Python set, not polyglot — polyglot has no
 * published 3B row, so our runs BECOME the first 3B polyglot row (see
 * anchors.ts: Stage 1 records an empty baseline here). Like the official
 * harness, Rust `#[ignore]` markers are stripped at grade time so all
 * tests run; the model never sees the test files (copied in only to grade).
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { runPythonScript } from './run-python'
import type { PublicBenchAdapter, PublicProblem } from './types'

export const AIDER_GRADE_FILE = 'grade_aider.py'

export type AiderLanguage = 'python' | 'rust'

export interface AiderTestFile {
  /** Workspace-relative path to materialize at grade time. */
  readonly path: string
  readonly content: string
}

export interface AiderPayload {
  readonly language: AiderLanguage
  readonly slug: string
  /** Files the model must write (contract gate). */
  readonly solutionFiles: string[]
  /** Test files embedded for the grader driver (never in the workspace). */
  readonly testFiles: AiderTestFile[]
  /** Shell command the grader driver executes. */
  readonly gradeCommand: string
}

interface LanguageConfig {
  /** Stub files copied into the workspace (model edits these). */
  stubFiles(exerciseDir: string, slug: string): Promise<Array<{ path: string; content: string }>>
  /** Test files embedded into the grader (kept out of the workspace). */
  testFiles(exerciseDir: string, slug: string): Promise<AiderTestFile[]>
  gradeCommand(slug: string): string
  solutionFiles(slug: string): string[]
  instructionsFile(exerciseDir: string): string
}

function snakeSlug(slug: string): string {
  return slug.replace(/-/g, '_')
}

const PYTHON: LanguageConfig = {
  stubFiles: async (dir, slug) => [
    { path: `${snakeSlug(slug)}.py`, content: await readFile(join(dir, `${snakeSlug(slug)}.py`), 'utf8') },
  ],
  testFiles: async (dir, slug) => [
    { path: `${snakeSlug(slug)}_test.py`, content: await readFile(join(dir, `${snakeSlug(slug)}_test.py`), 'utf8') },
  ],
  gradeCommand: slug => `python -m unittest ${snakeSlug(slug)}_test`,
  solutionFiles: slug => [`${snakeSlug(slug)}.py`],
  instructionsFile: dir => join(dir, '.docs', 'instructions.md'),
}

const RUST: LanguageConfig = {
  stubFiles: async dir => [
    { path: 'Cargo.toml', content: await readFile(join(dir, 'Cargo.toml'), 'utf8') },
    { path: 'src/lib.rs', content: await readFile(join(dir, 'src', 'lib.rs'), 'utf8') },
  ],
  testFiles: async dir => {
    const names = (await readdir(join(dir, 'tests'))).filter(n => n.endsWith('.rs'))
    const out: AiderTestFile[] = []
    for (const name of names) {
      out.push({
        path: `tests/${name}`,
        content: await readFile(join(dir, 'tests', name), 'utf8'),
      })
    }
    return out
  },
  gradeCommand: () => 'cargo test --offline',
  solutionFiles: () => ['src/lib.rs'],
  instructionsFile: dir => join(dir, '.docs', 'instructions.md'),
}

const CONFIGS: Record<AiderLanguage, LanguageConfig> = { python: PYTHON, rust: RUST }

export function encodePayload(p: AiderPayload): string {
  return JSON.stringify(p)
}

export function decodePayload(test: string): AiderPayload {
  return JSON.parse(test) as AiderPayload
}

/**
 * Grader driver written into every workspace. Materializes the hidden tests,
 * runs the language test command, exits 0 only when all tests pass. Python
 * drives every language (present on the grading machine); the model must not
 * modify or delete this file.
 */
export function aiderGraderSeed(problem: PublicProblem): string {
  const payload = decodePayload(problem.test)
  return [
    '"""Official board grader (generated by aider adapter). DO NOT MODIFY."""',
    'import pathlib, subprocess, sys',
    '',
    `PAYLOAD = ${JSON.stringify(payload)}`,
    '',
    'for entry in PAYLOAD["testFiles"]:',
    '    target = pathlib.Path(entry["path"])',
    '    target.parent.mkdir(parents=True, exist_ok=True)',
    '    text = entry["content"]',
    '    if PAYLOAD["language"] == "rust":',
    '        # Official-harness parity: Exercism ships most Rust tests',
    '        # #[ignore]d; strip the marker so the full suite runs.',
    '        text = "\\n".join(l for l in text.splitlines() if l.strip() != "#[ignore]")',
    '    target.write_text(text)',
    '',
    'proc = subprocess.run(',
    '    PAYLOAD["gradeCommand"], shell=True, capture_output=True, text=True)',
    'print(proc.stdout[-3000:])',
    'print(proc.stderr[-3000:], file=sys.stderr)',
    'sys.exit(proc.returncode)',
    '',
  ].join('\n')
}

export async function setupAiderWorkspace(
  workspace: string,
  problem: PublicProblem,
  datasetRoot: string = process.env.POLYGLOT_ROOT ?? '',
): Promise<void> {
  const payload = decodePayload(problem.test)
  const cfg = CONFIGS[payload.language]
  const exerciseDir = join(
    datasetRoot,
    payload.language,
    'exercises',
    'practice',
    payload.slug,
  )
  await mkdir(workspace, { recursive: true })
  for (const stub of await cfg.stubFiles(exerciseDir, payload.slug)) {
    const target = join(workspace, stub.path)
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, stub.content, 'utf8')
  }
  const instructions = await readFile(cfg.instructionsFile(exerciseDir), 'utf8')
  await writeFile(join(workspace, 'instructions.md'), instructions, 'utf8')
  await writeFile(join(workspace, AIDER_GRADE_FILE), aiderGraderSeed(problem), 'utf8')
}

export function rowToProblem(
  language: AiderLanguage,
  slug: string,
  instructions: string,
  payload: AiderPayload,
): PublicProblem {
  const cfg = CONFIGS[language]
  return {
    id: `aider/${language}/${slug}`,
    objective: [
      'Solve the programming exercise described below.',
      `Edit the stub file(s) in the workspace (${cfg.solutionFiles(slug).join(', ')}) to a complete, working solution.`,
      'The file grade_aider.py in the workspace is the official grader — do not modify or delete it.',
      'Hidden tests will be added at grade time; make the FULL behavior correct, not just the examples.',
      '',
      instructions.trimEnd(),
    ].join('\n'),
    test: encodePayload(payload),
    entryPoint: slug,
  }
}

export async function listAiderProblems(
  datasetRoot: string,
  languages: AiderLanguage[] = ['python', 'rust'],
): Promise<PublicProblem[]> {
  const problems: PublicProblem[] = []
  for (const language of languages) {
    const cfg = CONFIGS[language]
    const practice = join(datasetRoot, language, 'exercises', 'practice')
    let slugs: string[]
    try {
      slugs = (await readdir(practice, { withFileTypes: true }))
        .filter(e => e.isDirectory())
        .map(e => e.name)
        .sort()
    } catch {
      continue
    }
    for (const slug of slugs) {
      const dir = join(practice, slug)
      let instructions: string
      let testFiles: AiderTestFile[]
      try {
        instructions = await readFile(cfg.instructionsFile(dir), 'utf8')
        testFiles = await cfg.testFiles(dir, slug)
      } catch {
        continue
      }
      if (testFiles.length === 0) continue
      problems.push(
        rowToProblem(language, slug, instructions, {
          language,
          slug,
          solutionFiles: cfg.solutionFiles(slug),
          testFiles,
          gradeCommand: cfg.gradeCommand(slug),
        }),
      )
    }
  }
  return problems
}

export function createAiderAdapter(
  datasetRoot: string = process.env.POLYGLOT_ROOT ?? '',
  languages: AiderLanguage[] = ['python', 'rust'],
): PublicBenchAdapter {
  if (!datasetRoot) {
    throw new Error(
      'Polyglot dataset root required (POLYGLOT_ROOT or explicit argument).',
    )
  }
  return {
    name: 'aider',
    listProblems: async () => listAiderProblems(datasetRoot, languages),
    grade: async (workspace, problem) => {
      // The same driver the Factory verifies with, re-run authoritatively
      // in the workspace (imports/cargo resolve relatively; rust gets a
      // generous timeout for first-compile).
      const run = await runPythonScript(
        join(workspace, AIDER_GRADE_FILE),
        120_000,
        workspace,
      )
      return {
        problemId: problem.id,
        passed: run.exitCode === 0,
        detail: run.exitCode === 0 ? 'board tests passed' : run.outputTail,
      }
    },
  }
}
